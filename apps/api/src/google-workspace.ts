import { formatShort, scheduleProject, type GoogleFile, type GoogleLinks, type Project, type TaskStatus, type WorkspaceState } from "@hades/core";
import { googleAccessToken } from "./auth";
import type { StoredUser } from "./store";

/**
 * Google Workspace tools for the Hades agents: a Drive folder per event with a live tracker Sheet and a plan Doc,
 * two-way tracker sync (teammates edit Status in the Sheet, the progress agent pulls it back), and reading or
 * appending to any Doc or Sheet the organiser links.
 */
const DRIVE = "https://www.googleapis.com/drive/v3/files";
const SHEETS = "https://sheets.googleapis.com/v4/spreadsheets";
const DOCS = "https://docs.googleapis.com/v1/documents";

async function g<T>(token: string, url: string, init: RequestInit = {}): Promise<T> {
  const res = await fetch(url, { ...init, headers: { authorization: `Bearer ${token}`, "content-type": "application/json", ...init.headers } });
  const text = await res.text();
  const body = text ? JSON.parse(text) : {};
  if (res.status === 401 || res.status === 403) {
    throw Object.assign(new Error(`Google refused access (${body?.error?.message ?? res.status}). Reconnect Google Workspace, and check the file is shared with you.`), { status: 403, connect: true });
  }
  if (!res.ok) throw new Error(`Google error ${res.status}: ${body?.error?.message ?? text.slice(0, 200)}`);
  return body as T;
}

const now = () => new Date().toISOString();
const STATUS_LABEL: Record<TaskStatus, string> = { not_started: "Not started", in_progress: "In progress", blocked: "Blocked", done: "Done" };
const LABEL_STATUS: Record<string, TaskStatus> = { "not started": "not_started", todo: "not_started", "to do": "not_started", "in progress": "in_progress", doing: "in_progress", started: "in_progress", blocked: "blocked", stuck: "blocked", done: "done", complete: "done", completed: "done" };

function trackerRows(p: Project) {
  const sched = scheduleProject(p);
  const name = (id: string) => p.members.find((m) => m.id === id)?.name ?? id;
  const header = ["ID", "Task", "Owner", "Status", "Estimate (days)", "Start", "Finish", "Critical", "Depends on", "Notes"];
  const rows = p.tasks.map((t) => {
    const st = sched.tasks[t.id];
    return [
      t.id,
      t.title,
      p.members.find((m) => m.id === t.ownerId)?.email ? `${name(t.ownerId)} <${p.members.find((m) => m.id === t.ownerId)!.email}>` : name(t.ownerId),
      STATUS_LABEL[t.status],
      t.estimateDays ?? "",
      st?.startDate ?? "",
      st?.endDate ?? "",
      st?.onCriticalPath ? "Yes" : "",
      p.dependencies.filter((d) => d.to === t.id).map((d) => d.from).join(", "),
      "",
    ];
  });
  return [header, ...rows];
}

function planDocText(p: Project): string {
  const sched = scheduleProject(p);
  const name = (id: string) => p.members.find((m) => m.id === id)?.name ?? id;
  const lines = [
    p.name,
    "",
    `Event day: ${formatShort(p.deadline)} · Plan finishes ${formatShort(sched.finishDate)} · ${sched.feasible ? `${sched.bufferDays} working day(s) to spare` : "does not fit yet"}`,
    p.description ? `\n${p.description}` : "",
    "",
    "Team",
    ...p.members.map((m) => `• ${m.name} — ${m.role}${m.email ? ` · ${m.email}` : ""}`),
    "",
    "Plan",
    ...p.tasks.map((t) => {
      const st = sched.tasks[t.id];
      const owner = p.members.find((m) => m.id === t.ownerId);
      return `• ${t.id} ${t.title} — ${owner?.email ?? name(t.ownerId)}, ${st ? `${formatShort(st.startDate)} → ${formatShort(st.endDate)}` : ""}${st?.onCriticalPath ? " (critical)" : ""} [${STATUS_LABEL[t.status]}]`;
    }),
    "",
    `Critical path: ${sched.criticalPath.join(" → ") || "none"}`,
    "",
    "Generated by Hades AI · God of Event Management. Update statuses in the tracker sheet and Hades will pick them up.",
  ];
  return lines.filter((l) => l !== undefined).join("\n");
}

/** Shares a Drive file or folder with a teammate as an editor. Google emails them the link. */
export async function shareFile(user: StoredUser, fileId: string, email: string, message: string) {
  const token = await googleAccessToken(user);
  await g(token, `${DRIVE}/${fileId}/permissions?sendNotificationEmail=true&emailMessage=${encodeURIComponent(message)}&fields=id`, {
    method: "POST",
    body: JSON.stringify({ type: "user", role: "writer", emailAddress: email }),
  });
}

async function shareWithTeam(user: StoredUser, fileId: string, p: Project) {
  const shared: string[] = [];
  for (const m of p.members.slice(1)) {
    if (!m.email) continue;
    try {
      await shareFile(user, fileId, m.email, `${user.name} shared the "${p.name}" workspace with you on Hades AI.`);
      shared.push(m.email);
    } catch (e) {
      console.warn(`Sharing with ${m.email} failed:`, (e as Error).message);
    }
  }
  return shared;
}

async function moveTo(token: string, fileId: string, folderId: string) {
  await g(token, `${DRIVE}/${fileId}?addParents=${folderId}&removeParents=root&fields=id`, { method: "PATCH", body: "{}" });
}

async function createSheet(token: string, p: Project, folderId?: string): Promise<GoogleFile> {
  const sheet = await g<{ spreadsheetId: string; spreadsheetUrl: string; sheets: { properties: { sheetId: number } }[] }>(token, SHEETS, {
    method: "POST",
    body: JSON.stringify({ properties: { title: `${p.name} · Tracker (Hades)` }, sheets: [{ properties: { title: "Tasks", gridProperties: { frozenRowCount: 1 } } }] }),
  });
  await writeTracker(token, sheet.spreadsheetId, p);
  const sheetId = sheet.sheets[0].properties.sheetId;
  await ownerChips(token, sheet.spreadsheetId, sheetId, p);
  // Bold header and a Status dropdown so teammates can update progress from the Sheet.
  await g(token, `${SHEETS}/${sheet.spreadsheetId}:batchUpdate`, {
    method: "POST",
    body: JSON.stringify({
      requests: [
        { repeatCell: { range: { sheetId, startRowIndex: 0, endRowIndex: 1 }, cell: { userEnteredFormat: { textFormat: { bold: true }, backgroundColor: { red: 0.93, green: 0.94, blue: 0.97 } } }, fields: "userEnteredFormat(textFormat,backgroundColor)" } },
        {
          setDataValidation: {
            range: { sheetId, startRowIndex: 1, endRowIndex: 500, startColumnIndex: 3, endColumnIndex: 4 },
            rule: { condition: { type: "ONE_OF_LIST", values: Object.values(STATUS_LABEL).map((v) => ({ userEnteredValue: v })) }, showCustomUi: true, strict: false },
          },
        },
        { autoResizeDimensions: { dimensions: { sheetId, dimension: "COLUMNS", startIndex: 0, endIndex: 10 } } },
      ],
    }),
  }).catch(() => undefined);
  if (folderId) await moveTo(token, sheet.spreadsheetId, folderId);
  return { id: sheet.spreadsheetId, name: `${p.name} · Tracker`, url: sheet.spreadsheetUrl, kind: "sheet", role: "tracker", at: now() };
}

/** Turns the Owner column into @-mention person chips. Optional: plain "Name <email>" stays if Sheets refuses. */
async function ownerChips(token: string, spreadsheetId: string, sheetId: number, p: Project) {
  const rows = p.tasks.map((t) => {
    const m = p.members.find((x) => x.id === t.ownerId);
    return m?.email
      ? { values: [{ userEnteredValue: { stringValue: "@" }, chipRuns: [{ startIndex: 0, chip: { personProperties: { email: m.email, displayFormat: "DEFAULT" } } }] }] }
      : { values: [{ userEnteredValue: { stringValue: m?.name ?? t.ownerId } }] };
  });
  await g(token, `${SHEETS}/${spreadsheetId}:batchUpdate`, {
    method: "POST",
    body: JSON.stringify({ requests: [{ updateCells: { rows, fields: "userEnteredValue,chipRuns", start: { sheetId, rowIndex: 1, columnIndex: 2 } } }] }),
  }).catch((e) => console.warn("Sheets person chips skipped:", (e as Error).message));
}

async function writeTracker(token: string, sheetId: string, p: Project) {
  await g(token, `${SHEETS}/${sheetId}/values/Tasks!A1:J500:clear`, { method: "POST", body: "{}" });
  await g(token, `${SHEETS}/${sheetId}/values/Tasks!A1?valueInputOption=USER_ENTERED`, { method: "PUT", body: JSON.stringify({ values: trackerRows(p) }) });
}

/** Replaces every email in the doc with an @-mention person chip. One atomic batch: all or nothing. */
async function docChips(token: string, documentId: string, text: string) {
  const hits: { start: number; end: number; email: string }[] = [];
  const re = /[\w.+-]+@[\w-]+\.[\w.]+/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text))) hits.push({ start: m.index + 1, end: m.index + 1 + m[0].length, email: m[0] });
  if (!hits.length) return;
  const requests = hits
    .sort((a, b) => b.start - a.start)
    .flatMap((h) => [
      { deleteContentRange: { range: { startIndex: h.start, endIndex: h.end } } },
      { insertPerson: { personProperties: { email: h.email }, location: { index: h.start } } },
    ]);
  await g(token, `${DOCS}/${documentId}:batchUpdate`, { method: "POST", body: JSON.stringify({ requests }) }).catch((e) =>
    console.warn("Docs person chips skipped:", (e as Error).message),
  );
}

async function createDoc(token: string, p: Project, folderId?: string): Promise<GoogleFile> {
  const doc = await g<{ documentId: string }>(token, DOCS, { method: "POST", body: JSON.stringify({ title: `${p.name} · Plan (Hades)` }) });
  const text = planDocText(p);
  const titleEnd = p.name.length + 1;
  await g(token, `${DOCS}/${doc.documentId}:batchUpdate`, {
    method: "POST",
    body: JSON.stringify({
      requests: [
        { insertText: { location: { index: 1 }, text } },
        { updateParagraphStyle: { range: { startIndex: 1, endIndex: titleEnd }, paragraphStyle: { namedStyleType: "TITLE" }, fields: "namedStyleType" } },
      ],
    }),
  });
  await docChips(token, doc.documentId, text);
  if (folderId) await moveTo(token, doc.documentId, folderId);
  return { id: doc.documentId, name: `${p.name} · Plan`, url: `https://docs.google.com/document/d/${doc.documentId}/edit`, kind: "doc", role: "plan", at: now() };
}

/** Drive folder + tracker Sheet + plan Doc for the event. Reuses whatever already exists. */
export async function createEventWorkspace(user: StoredUser, w: WorkspaceState): Promise<GoogleLinks> {
  const token = await googleAccessToken(user);
  const links: GoogleLinks = { files: [], ...w.google };
  if (!links.folder) {
    const f = await g<{ id: string }>(token, `${DRIVE}?fields=id`, { method: "POST", body: JSON.stringify({ name: `${w.project.name} · Hades AI`, mimeType: "application/vnd.google-apps.folder" }) });
    links.folder = { id: f.id, name: `${w.project.name} · Hades AI`, url: `https://drive.google.com/drive/folders/${f.id}`, kind: "folder", role: "workspace", at: now() };
  }
  if (!links.tracker) links.tracker = await createSheet(token, w.project, links.folder.id);
  else await writeTracker(token, links.tracker.id, w.project);
  if (!links.planDoc) links.planDoc = await createDoc(token, w.project, links.folder.id);
  links.sharedWith = await shareWithTeam(user, links.folder.id, w.project);
  return links;
}

export async function syncTracker(user: StoredUser, w: WorkspaceState): Promise<GoogleLinks> {
  const token = await googleAccessToken(user);
  const links: GoogleLinks = { files: [], ...w.google };
  if (!links.tracker) links.tracker = await createSheet(token, w.project, links.folder?.id);
  else await writeTracker(token, links.tracker.id, w.project);
  return links;
}

export async function createPlanDoc(user: StoredUser, w: WorkspaceState): Promise<GoogleFile> {
  return createDoc(await googleAccessToken(user), w.project, w.google?.folder?.id);
}

/** Reads Status (and Owner/Estimate) edits from the tracker sheet. Returns the changes to apply. */
export async function pullTracker(user: StoredUser, w: WorkspaceState): Promise<{ taskId: string; status?: TaskStatus; estimateDays?: number }[]> {
  if (!w.google?.tracker) throw Object.assign(new Error("There's no tracker sheet yet. Say \"Create a Google workspace\" first."), { status: 409 });
  const token = await googleAccessToken(user);
  const data = await g<{ values?: string[][] }>(token, `${SHEETS}/${w.google.tracker.id}/values/Tasks!A2:E500`);
  const out: { taskId: string; status?: TaskStatus; estimateDays?: number }[] = [];
  for (const row of data.values ?? []) {
    const [id, , , statusLabel, est] = row;
    const t = w.project.tasks.find((x) => x.id === id);
    if (!t) continue;
    const status = LABEL_STATUS[(statusLabel ?? "").trim().toLowerCase()];
    const estimate = est !== undefined && est !== "" ? Number(est) : undefined;
    const change: { taskId: string; status?: TaskStatus; estimateDays?: number } = { taskId: t.id };
    if (status && status !== t.status) change.status = status;
    if (estimate !== undefined && Number.isFinite(estimate) && estimate > 0 && estimate !== t.estimateDays) change.estimateDays = estimate;
    if (change.status || change.estimateDays) out.push(change);
  }
  return out;
}

export function parseGoogleUrl(url: string): { kind: "doc" | "sheet"; id: string } | null {
  const m = url.match(/docs\.google\.com\/(document|spreadsheets)\/d\/([\w-]+)/);
  return m ? { kind: m[1] === "document" ? "doc" : "sheet", id: m[2] } : null;
}

interface DocBody {
  title: string;
  body: { content: { endIndex?: number; paragraph?: { elements: { textRun?: { content: string } }[] }; table?: { tableRows: { tableCells: { content: { paragraph?: { elements: { textRun?: { content: string } }[] } }[] }[] }[] } }[] };
}

/** Reads a Doc or Sheet the organiser can access. Returns its title and plain text (sheets as rows). */
export async function readGoogleFile(user: StoredUser, url: string): Promise<{ file: GoogleFile; text: string; rows?: string[][] }> {
  const ref = parseGoogleUrl(url);
  if (!ref) throw Object.assign(new Error("That isn't a Google Docs or Sheets link."), { status: 400 });
  const token = await googleAccessToken(user);
  if (ref.kind === "doc") {
    const doc = await g<DocBody>(token, `${DOCS}/${ref.id}`);
    const para = (p?: { elements: { textRun?: { content: string } }[] }) => (p?.elements ?? []).map((e) => e.textRun?.content ?? "").join("");
    const text = doc.body.content
      .map((c) => (c.paragraph ? para(c.paragraph) : c.table ? c.table.tableRows.map((r) => r.tableCells.map((cell) => cell.content.map((x) => para(x.paragraph).trim()).join(" ")).join(" | ")).join("\n") + "\n" : ""))
      .join("");
    return { file: { id: ref.id, name: doc.title, url: `https://docs.google.com/document/d/${ref.id}/edit`, kind: "doc", role: "linked", at: now() }, text };
  }
  const meta = await g<{ properties: { title: string }; sheets: { properties: { title: string } }[] }>(token, `${SHEETS}/${ref.id}?fields=properties.title,sheets.properties.title`);
  const tab = meta.sheets[0]?.properties.title ?? "Sheet1";
  const data = await g<{ values?: string[][] }>(token, `${SHEETS}/${ref.id}/values/${encodeURIComponent(`'${tab}'!A1:Z300`)}`);
  const rows = data.values ?? [];
  return {
    file: { id: ref.id, name: meta.properties.title, url: `https://docs.google.com/spreadsheets/d/${ref.id}/edit`, kind: "sheet", role: "linked", at: now() },
    text: rows.map((r) => r.join(" | ")).join("\n"),
    rows,
  };
}

/** Appends a paragraph to a Doc, or a row to a Sheet. */
export async function appendToGoogleFile(user: StoredUser, url: string, text: string): Promise<GoogleFile> {
  const ref = parseGoogleUrl(url);
  if (!ref) throw Object.assign(new Error("That isn't a Google Docs or Sheets link."), { status: 400 });
  const token = await googleAccessToken(user);
  const stamp = new Date().toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short", timeZone: "Asia/Kolkata" });
  if (ref.kind === "doc") {
    const doc = await g<DocBody>(token, `${DOCS}/${ref.id}`);
    await g(token, `${DOCS}/${ref.id}:batchUpdate`, { method: "POST", body: JSON.stringify({ requests: [{ insertText: { endOfSegmentLocation: {}, text: `\n${text} — Hades AI, ${stamp}\n` } }] }) });
    return { id: ref.id, name: doc.title, url: `https://docs.google.com/document/d/${ref.id}/edit`, kind: "doc", role: "linked", at: now() };
  }
  const meta = await g<{ properties: { title: string }; sheets: { properties: { title: string } }[] }>(token, `${SHEETS}/${ref.id}?fields=properties.title,sheets.properties.title`);
  const tab = meta.sheets[0]?.properties.title ?? "Sheet1";
  await g(token, `${SHEETS}/${ref.id}/values/${encodeURIComponent(`'${tab}'!A1`)}:append?valueInputOption=USER_ENTERED&insertDataOption=INSERT_ROWS`, {
    method: "POST",
    body: JSON.stringify({ values: [[stamp, ...text.split("|").map((s) => s.trim())]] }),
  });
  return { id: ref.id, name: meta.properties.title, url: `https://docs.google.com/spreadsheets/d/${ref.id}/edit`, kind: "sheet", role: "linked", at: now() };
}

/** Turns bullet or checklist lines of a document into task titles the agent can add. */
export function extractTasks(text: string): string[] {
  return text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => /^([-*•▢☐□]|\d+[.)]|\[ ?\])\s+/.test(l))
    .map((l) => l.replace(/^([-*•▢☐□]|\d+[.)]|\[ ?\])\s+/, "").trim())
    .filter((l) => l.length > 3 && l.length < 120)
    .slice(0, 15);
}
